-- ---------- Listes de reference (modifiables par les admins) ----------

create table if not exists public.familles (
  id serial primary key,
  nom text not null unique,
  couleur text,
  ordre int not null default 0,
  actif boolean not null default true
);
alter table public.familles add column if not exists couleur text;

create table if not exists public.niveaux (
  id serial primary key,
  famille_id int not null references public.familles(id) on delete cascade,
  nom text not null,
  ordre int not null default 0,
  actif boolean not null default true
);

create table if not exists public.championnats (
  id serial primary key,
  nom text not null unique,
  ordre int not null default 0,
  actif boolean not null default true
);

create table if not exists public.juges (
  id serial primary key,
  nom text not null,
  secteur text,
  actif boolean not null default true
);

-- ---------- Organisateurs (un par compte) ----------

create table if not exists public.organisateurs (
  id uuid primary key references auth.users(id) on delete cascade,
  nom_club text not null default '',
  responsable text,
  email text,
  telephone text,
  region text,
  departement text,
  commune_habituelle text,
  adresse_habituelle text,
  site_web text,
  epreuves_proposees int[] not null default '{}',
  statut text not null default 'en_attente'
    check (statut in ('en_attente', 'valide', 'refuse')),
  role text not null default 'organisateur'
    check (role in ('organisateur', 'admin')),
  created_at timestamptz not null default now()
);

-- ---------- Concours ----------

create table if not exists public.concours (
  id bigint generated by default as identity primary key,
  organisateur_id uuid not null default auth.uid()
    references public.organisateurs(id) on delete cascade,
  titre text,
  date_debut date not null,
  date_fin date,
  commune text not null,
  departement text,
  region text,
  adresse text,
  niveaux int[] not null default '{}',
  juges int[] not null default '{}',
  juge_autre text,
  championnats int[] not null default '{}',
  inscription_ouverture date,
  inscription_cloture date,
  inscription_lien text,
  contact text,
  places int,
  statut text not null default 'provisoire'
    check (statut in ('provisoire', 'confirme', 'annule')),
  remarques text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dates_ok check (date_fin is null or date_fin >= date_debut),
  constraint inscriptions_ok check (
    inscription_cloture is null or inscription_ouverture is null
    or inscription_cloture >= inscription_ouverture)
);

create index if not exists concours_date_idx on public.concours (date_debut);

-- ---------- Fonctions utilitaires ----------

create or replace function public.est_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.organisateurs
    where id = auth.uid() and role = 'admin' and statut = 'valide');
$$;

create or replace function public.est_valide()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.organisateurs
    where id = auth.uid() and statut = 'valide');
$$;

create or replace function public.org_valide(uid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.organisateurs where id = uid and statut = 'valide');
$$;

-- Cree automatiquement la fiche organisateur a l'inscription
create or replace function public.nouvel_utilisateur()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.organisateurs (id, email, nom_club)
  values (new.id, new.email, coalesce(new.raw_user_meta_data ->> 'nom_club', ''));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.nouvel_utilisateur();

-- Empeche un organisateur de modifier lui-meme son statut ou son role.
-- (Depuis le SQL Editor, auth.uid() est vide : la modification est autorisee,
--  c'est comme ca qu'on nomme le premier admin.)
create or replace function public.protege_statut()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not public.est_admin() then
    new.statut := old.statut;
    new.role := old.role;
  end if;
  return new;
end $$;

drop trigger if exists protege_statut on public.organisateurs;
create trigger protege_statut
  before update on public.organisateurs
  for each row execute function public.protege_statut();

create or replace function public.maj_date()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists maj_date on public.concours;
create trigger maj_date
  before update on public.concours
  for each row execute function public.maj_date();

-- ---------- Droits d'acces ----------

grant usage on schema public to anon, authenticated;
grant select on public.familles, public.niveaux, public.championnats,
  public.juges, public.organisateurs, public.concours to anon, authenticated;
grant insert, update, delete on public.familles, public.niveaux,
  public.championnats, public.juges, public.organisateurs, public.concours
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.familles enable row level security;
alter table public.niveaux enable row level security;
alter table public.championnats enable row level security;
alter table public.juges enable row level security;
alter table public.organisateurs enable row level security;
alter table public.concours enable row level security;

-- Listes de reference : lecture pour tous, ecriture admins
do $$
declare t text;
begin
  foreach t in array array['familles', 'niveaux', 'championnats', 'juges'] loop
    execute format('drop policy if exists lecture on public.%I', t);
    execute format('drop policy if exists ecriture_admin on public.%I', t);
    execute format('create policy lecture on public.%I for select using (true)', t);
    execute format('create policy ecriture_admin on public.%I for all
      using (public.est_admin()) with check (public.est_admin())', t);
  end loop;
end $$;

-- Organisateurs : les fiches validees sont publiques,
-- chacun voit et modifie la sienne, les admins voient tout.
drop policy if exists lecture on public.organisateurs;
create policy lecture on public.organisateurs for select
  using (statut = 'valide' or id = auth.uid() or public.est_admin());

drop policy if exists modif on public.organisateurs;
create policy modif on public.organisateurs for update
  using (id = auth.uid() or public.est_admin())
  with check (id = auth.uid() or public.est_admin());

drop policy if exists suppr_admin on public.organisateurs;
create policy suppr_admin on public.organisateurs for delete
  using (public.est_admin());

-- Concours : publics si l'organisateur est valide,
-- chaque organisateur valide gere les siens, les admins gerent tout.
drop policy if exists lecture on public.concours;
create policy lecture on public.concours for select
  using (public.org_valide(organisateur_id)
         or organisateur_id = auth.uid() or public.est_admin());

drop policy if exists ajout on public.concours;
create policy ajout on public.concours for insert
  with check ((organisateur_id = auth.uid() and public.est_valide())
              or public.est_admin());

drop policy if exists modif on public.concours;
create policy modif on public.concours for update
  using ((organisateur_id = auth.uid() and public.est_valide()) or public.est_admin())
  with check ((organisateur_id = auth.uid() and public.est_valide()) or public.est_admin());

drop policy if exists suppr on public.concours;
create policy suppr on public.concours for delete
  using ((organisateur_id = auth.uid() and public.est_valide()) or public.est_admin());

